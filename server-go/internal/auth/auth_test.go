func TestChangePasswordDestroysOthers(t *testing.T) {
	_, prod := testService(t)
	if _, err := prod.Exec(`INSERT INTO users (id, username, password_hash, created_at) VALUES ('u1','n','x',1)`); err != nil {
		t.Fatal(err)
	}
	if _, _, err := CreateSession(prod, "u1", ""); err != nil {
		t.Fatal(err)
	}
	sid2, _, err := CreateSession(prod, "u1", "")
	if err != nil {
		t.Fatal(err)
	}
	seed, err := bcrypt.GenerateFromPassword([]byte("secret"), 10)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := prod.Exec("UPDATE users SET password_hash = ? WHERE id = ?", string(seed), "u1"); err != nil {
		t.Fatal(err)
	}
	res, err := ChangePassword(prod, "u1", "not-the-secret", "newpassword-10")
	if err != nil || res != "wrong-current" {
		t.Fatalf("wrong current must be rejected: %v %v", res, err)
	}
	res, err = ChangePassword(prod, "u1", "secret", "newpassword-10")
	if err != nil || res != "ok" {
		t.Fatalf("change must succeed: %v %v", res, err)
	}
	if err := DestroyOtherSessions(prod, "u1", sid2); err != nil {
		t.Fatal(err)
	}
	var count int
	if err := prod.QueryRow("SELECT COUNT(*) FROM sessions WHERE user_id='u1'").Scan(&count); err != nil {
		t.Fatal(err)
	}
	if count != 1 {
		t.Fatalf("only the current session must survive, got %d", count)
	}
}
