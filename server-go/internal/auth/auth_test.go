func TestCookieSignature(t *testing.T) {
	s, _ := testService(t)
	v := CookieValue(s.Secret, "session-1")
	if !strings.HasSuffix(v, "."+hmacHex(s.Secret, "session-1")) {
		t.Fatal("cookie must be id.hmac")
	}
	req := httptest.NewRequest(http.MethodGet, "/", nil)
	req.AddCookie(&http.Cookie{Name: CookieName, Value: v})
	// No session row yet: ResolveSession returns nil (signature alone is not
	// enough).
	if res := s.ResolveSession(req); res != nil {
		t.Fatal("cookie without session row must not resolve")
	}
	req.AddCookie(&http.Cookie{Name: CookieName, Value: "session-1.deadbeef"})
	if res := s.ResolveSession(req); res != nil {
		t.Fatal("bad signature must not resolve")
	}
}

func TestResolveSessionAndRenewal(t *testing.T) {
	s, prod := testService(t)
	if _, err := prod.Exec(`INSERT INTO users (id, username, password_hash, role, created_at)
		VALUES ('u1','nacho','x','admin',1)`); err != nil {
		t.Fatal(err)
	}
	sid, csrf, err := CreateSession(prod, "u1", "UA-1")
	if err != nil {
		t.Fatal(err)
	}
	req := httptest.NewRequest(http.MethodGet, "/api/auth/me", nil)
	req.AddCookie(&http.Cookie{Name: CookieName, Value: CookieValue(s.Secret, sid)})
	req.Header.Set("User-Agent", "UA-1")
	res := s.ResolveSession(req)
	if res == nil || res.User == nil || res.User.Username != "nacho" {
		t.Fatalf("session must resolve: %+v", res)
	}
	if res.CSRFToken != csrf {
		t.Fatalf("csrf token mismatch")
	}
	if res.Renew {
		t.Fatal("fresh session must not need renewal")
	}

	// Below half TTL: renewal flag set.
	if _, err := prod.Exec("UPDATE sessions SET expires_at = ? WHERE id = ?",
		time.Now().UnixMilli()+int64((SessionTTL/4).Milliseconds()), sid); err != nil {
		t.Fatal(err)
	}
	res = s.ResolveSession(req)
	if res == nil || !res.Renew {
		t.Fatal("session under threshold must be flagged for renewal")
	}

	// Expired sessions do not resolve.
	if _, err := prod.Exec("UPDATE sessions SET expires_at = ? WHERE id = ?",
		time.Now().UnixMilli()-1000, sid); err != nil {
		t.Fatal(err)
	}
	if res := s.ResolveSession(req); res != nil {
		t.Fatal("expired session must not resolve")
	}
}

func TestRequireAuthMiddleware(t *testing.T) {
	s, _ := testService(t)
	called := false
	handler := s.RequireAuth(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		called = true
	}))
	// Public path passes without session.
	req := httptest.NewRequest(http.MethodPost, "/api/auth/login", nil)
	handler.ServeHTTP(httptest.NewRecorder(), req)
	if !called {
		t.Fatal("public path must pass")
	}
	// Private path without session: 401 AUTH_REQUIRED envelope.
	called = false
	req = httptest.NewRequest(http.MethodGet, "/api/tasks", nil)
	rec := httptest.NewRecorder()
	handler.ServeHTTP(rec, req)
	if called || rec.Code != http.StatusUnauthorized {
		t.Fatalf("private path must 401 (called=%v code=%d)", called, rec.Code)
	}
	if !strings.Contains(rec.Body.String(), "AUTH_REQUIRED") {
		t.Fatalf("envelope must carry the code: %s", rec.Body.String())
	}
}

func TestLoginLockout(t *testing.T) {
	_, prod := testService(t)
	req := httptest.NewRequest(http.MethodPost, "/api/auth/login", nil)
	req.RemoteAddr = "192.168.1.55:1234"
	for i := 0; i < 4; i++ {
		if LoginRateLimited(prod, req, "") {
			t.Fatalf("attempt %d must not be locked yet", i+1)
		}
		if err := RegisterLoginFail(prod, req, ""); err != nil {
			t.Fatal(err)
		}
	}
	if LoginRateLimited(prod, req, "") {
		t.Fatal("4 failures must not lock yet (lock on the 5th)")
	}
	if err := RegisterLoginFail(prod, req, ""); err != nil {
		t.Fatal(err)
	}
	if !LoginRateLimited(prod, req, "") {
		t.Fatal("5 failures must lock the IP")
	}
	if err := LoginOK(prod, req, ""); err != nil {
		t.Fatal(err)
	}
	if LoginRateLimited(prod, req, "") {
		t.Fatal("login OK must clear the lockout")
	}
}

func TestTrustedProxyForwardedFor(t *testing.T) {
	req := httptest.NewRequest(http.MethodPost, "/api/auth/login", nil)
	req.RemoteAddr = "10.0.0.9:5555"
	req.Header.Set("X-Forwarded-For", "203.0.113.7, 10.0.0.1")
	if got := ClientIP(req, ""); got != "10.0.0.9" {
		t.Fatalf("without TRUSTED_PROXY the peer must be used, got %q", got)
	}
	if got := ClientIP(req, "10.0.0.9"); got != "203.0.113.7" {
		t.Fatalf("trusted proxy must take the first XFF value, got %q", got)
	}
}

func TestIsPublicPath(t *testing.T) {
	cases := []struct {
		path, method string
		want         bool
	}{
		{"/api/auth/login", http.MethodPost, true},
		{"/api/auth/logout", http.MethodPost, true},
		{"/api/auth/demo", http.MethodPost, true},
		{"/api/settings/demo", http.MethodGet, true},
		{"/api/settings/demo", http.MethodPost, false},
		{"/api/invite/abc", http.MethodGet, true},
		{"/api/invite/abc", http.MethodPut, true},
		{"/api/invite/abc/comments", http.MethodPost, true},
		{"/api/invite/abc/accept", http.MethodPost, false},
		{"/api/ha/tasks/1", http.MethodPost, true},
		{"/api/tasks", http.MethodGet, false},
	}
	for _, c := range cases {
		if got := IsPublicPath(c.path, c.method); got != c.want {
			t.Errorf("IsPublicPath(%q,%q) = %v, want %v", c.path, c.method, got, c.want)
		}
	}
}

