//
//	bcrypt.hashSync('deltos-interop-pass-1', 10)
//
// Proves golang.org/x/crypto/bcrypt accepts a Node hash (Helios lesson).
const nodeBcryptHash = "$2b$10$K/6jmSwQVBeUijkzkxA4GuMB47rKipc5CcADhxUG.dxZHbDRWyPiO"

const nodeBcryptPassword = "deltos-interop-pass-1"

func TestBcryptAcceptsNodeHash(t *testing.T) {
	if bcrypt.CompareHashAndPassword([]byte(nodeBcryptHash), []byte(nodeBcryptPassword)) != nil {
		t.Fatal("Go bcrypt must validate the bcryptjs fixture")
	}
	if bcrypt.CompareHashAndPassword([]byte(nodeBcryptHash), []byte("wrong")) == nil {
		t.Fatal("Go bcrypt must reject a wrong password")
	}
}

